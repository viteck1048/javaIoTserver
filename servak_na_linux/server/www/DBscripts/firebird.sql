CREATE TABLE MASHYNES
(
    M_ID INT NOT NULL PRIMARY KEY,
    NAME VARCHAR(60) NOT NULL CHECK (NAME SIMILAR TO '[ -~]+'),
    M1 VARCHAR(1000) NOT NULL CHECK (M1 SIMILAR TO '[ 0-9]+'),
    M2 VARCHAR(1000) DEFAULT NULL CHECK (M2 SIMILAR TO '[ 0-9]+')
);
---
CREATE GENERATOR gen_m_id;
---
SET GENERATOR gen_m_id TO 0;
---
CREATE TRIGGER M_BI FOR MASHYNES
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
if (NEW.M_ID is NULL) then NEW.M_ID = GEN_ID(GEN_M_ID, 1);
END
---


CREATE TABLE LIRY
(
    L_ID INT NOT NULL PRIMARY KEY,
    M_ID INT NOT NULL,
    NAME VARCHAR(60) DEFAULT NULL,
    MAGAZ INT DEFAULT 1 CHECK (MAGAZ IN (1, 2)),
    FORM VARCHAR(98) NOT NULL CHECK (FORM SIMILAR TO '[-()\\+*\/.=0-9a-z]+'),
    FORM_ZV VARCHAR(98) NOT NULL CHECK (FORM_ZV SIMILAR TO '[-()\\+*\/.=0-9a-z]+'),
    BR_KOL_LIR INT DEFAULT 4 CHECK (BR_KOL_LIR >= 2 AND BR_KOL_LIR <= 4)
);
---
